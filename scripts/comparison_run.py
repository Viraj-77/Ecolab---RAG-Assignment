def run_single(query: str) -> dict:
    memory = make_memory()
    start = time.perf_counter()
    response = chat(memory, query)
    latency = time.perf_counter() - start
    messages = memory.messages()
    # cloud: tool role; local: user message injected as "Tool result for ..."
    tool_called = any(
        m.get("role") == "tool"
        or (m.get("role") == "user" and str(m.get("content", "")).startswith("Tool result for "))
        for m in messages
    )
    return {"response": response, "latency_s": round(latency, 3), "tool_called": tool_called}


def main():
    print(f"Running comparison for profile: {LLM_PROFILE}")
    results = []

    for item in PROMPT_SET:
        print(f"  [{item['id']}] {item['query'][:60]}...", flush=True)
        try:
            out = run_single(item["query"])
        except Exception as e:
            out = {"response": f"ERROR: {e}", "latency_s": 0.0, "tool_called": False}

        results.append({
            "id": item["id"],
            "type": item["type"],
            "query": item["query"],
            "profile": LLM_PROFILE,
            **out,
        })
        print(f"       latency={out['latency_s']}s  tool={out['tool_called']}", flush=True)

    out_path = f"scripts/results_{LLM_PROFILE}.json"
    with open(out_path, "w") as f:
        json.dump(results, f, indent=2)
    print(f"\nResults saved to {out_path}")


if __name__ == "__main__":
    main()
